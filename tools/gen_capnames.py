#!/usr/bin/env python3
"""Write tu/capnames.cpp: terminfo's standard capability names in the
order compiled entries store them, read from ncurses' libtinfo (the
boolnames, numnames and strnames arrays). SVR4 systems such as IRIX use
the same order for the capabilities they have. Run it again only if a
new ncurses adds standard capabilities."""
import ctypes, ctypes.util, sys

lib = ctypes.CDLL(ctypes.util.find_library("tinfo") or "libtinfo.so")

def names(sym):
    out = []
    arr = (ctypes.c_char_p * 1000).in_dll(lib, sym)
    for x in arr:
        if x is None:
            break
        out.append(x.decode())
    return out

def emit(f, var, items):
    f.write("const char* const %s[] = {\n" % var)
    line = "   "
    for n in items:
        tok = ' "%s",' % n
        if len(line) + len(tok) > 78:
            f.write(line + "\n")
            line = "   "
        line += tok
    f.write(line + "\n    0\n};\n")

out = sys.argv[1] if len(sys.argv) > 1 else "tu/capnames.cpp"
with open(out, "w") as f:
    f.write("/* Generated by tools/gen_capnames.py from ncurses' libtinfo: terminfo's\n"
            " * standard capability names in compiled-entry order. Do not edit. */\n")
    f.write('#include "capnames.h"\n\nnamespace tu {\n\n')
    emit(f, "k_bool_names", names("boolnames"))
    f.write("\n")
    emit(f, "k_num_names", names("numnames"))
    f.write("\n")
    emit(f, "k_str_names", names("strnames"))
    f.write("\n} /* namespace tu */\n")
